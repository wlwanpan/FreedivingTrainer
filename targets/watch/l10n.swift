import Foundation

enum L10n {
    static var language = "en"

    static func t(_ key: String, _ vars: [String: String] = [:]) -> String {
        let table = catalogs[language] ?? catalogs["en"]!
        var template = table[key] ?? catalogs["en"]?[key] ?? key
        for (name, value) in vars {
            template = template.replacingOccurrences(of: "{\(name)}", with: value)
        }
        return template
    }

    static func phase(_ key: String) -> String {
        switch key {
        case "Hold": return t("holdPhase")
        case "Rest": return t("restPhase")
        case "Breathe": return t("breathePhase")
        default: return key
        }
    }

    static func holdDetail(tableType: String, time: String, count: Int) -> String {
        let prefix = tableType == "o2" ? t("holdsFrom", ["time": time]) : t("hold", ["time": time])
        let rounds = count == 1 ? t("round") : t("rounds")
        return t("holdRounds", ["prefix": prefix, "count": "\(count)", "rounds": rounds])
    }

    static func apply(_ value: String?) {
        guard let value, catalogs[value] != nil else { return }
        language = value
    }
}

